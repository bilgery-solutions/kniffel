const assert = require('node:assert/strict');
const R = require('../rules.js');
const dice = (...values) => values;
const score = (type, ...values) => R.scoreDice(type, values);
assert.equal(R.KEYS.length,13);
assert.equal(score('ones',1,1,2,3,4),2);
assert.equal(score('sixes',6,6,6,6,1),24);
assert.equal(score('threeKind',3,3,3,4,5),18);
assert.equal(score('threeKind',1,1,2,3,4),0);
assert.equal(score('fourKind',2,2,2,2,5),13);
assert.equal(score('fourKind',2,2,2,5,5),0);
assert.equal(score('fullHouse',3,3,3,5,5),25);
assert.equal(score('fullHouse',5,5,5,5,5),0);
assert.equal(score('smallStraight',1,2,3,4,4),30);
assert.equal(score('smallStraight',2,3,4,5,6),30);
assert.equal(score('smallStraight',1,1,2,3,5),0);
assert.equal(score('largeStraight',1,2,3,4,5),40);
assert.equal(score('largeStraight',2,3,4,5,6),40);
assert.equal(score('largeStraight',1,2,3,4,4),0);
assert.equal(score('kniffel',6,6,6,6,6),50);
assert.equal(score('chance',1,2,3,4,5),15);
const s = R.emptyScores();
assert.equal(R.isBonusKniffel(s,dice(6,6,6,6,6)),false);
s.kniffel=0;
assert.equal(R.isBonusKniffel(s,dice(6,6,6,6,6)),false);
s.kniffel=50;
assert.equal(R.isBonusKniffel(s,dice(6,6,6,6,6)),true);
assert.equal(R.scoreForTurn('fullHouse',dice(6,6,6,6,6),s),25);
assert.equal(R.scoreForTurn('largeStraight',dice(6,6,6,6,6),s),40);
assert.equal(R.scoreForTurn('ones',dice(6,6,6,6,6),s),5);
assert.equal(R.scoreForTurn('threeKind',dice(6,6,6,6,6),s),30);
s.ones=5;
assert.equal(R.scoreForTurn('ones',dice(6,6,6,6,6),s),null);
const completed=R.emptyScores();
Object.assign(completed,{ones:3,twos:6,threes:9,fours:12,fives:15,sixes:18,threeKind:20,fourKind:24,fullHouse:25,smallStraight:30,largeStraight:40,kniffel:50,chance:20});
assert.deepEqual(R.totals({scores:completed,bonusKniffels:2}),{upper:63,bonus:35,lower:209,extra:100,total:407,filled:13});
console.log('All Kniffel scoring tests passed.');
